async function loadInitialData() {
  try {
    const res = await getInitialData();
    if (!res || !res.success) throw new Error("getInitialData failed");

    // ── Hero slider media (admin-controlled, image or video, falls
    //    back to the default bundled photos when a slot isn't set) ──
    if (res.settings) {
      const slideEls = document.querySelectorAll("#heroSlider .hero-slide");
      slideEls.forEach((slideEl, i) => {
        const url = res.settings["hero_slide_" + (i + 1)];
        if (!url) return;
        const isVideo = /\.(mp4|webm|mov|m4v)(\?.*)?$/i.test(url);
        const existing = slideEl.querySelector("img, video");
        if (isVideo) {
          if (existing && existing.tagName === "VIDEO") {
            existing.src = url;
          } else {
            const video = document.createElement("video");
            video.src = url;
            video.autoplay = true;
            video.muted = true;
            video.loop = true;
            video.playsInline = true;
            if (existing) existing.replaceWith(video);
            else slideEl.appendChild(video);
          }
        } else if (existing && existing.tagName === "IMG") {
          existing.src = url;
        } else {
          const img = document.createElement("img");
          img.src = url;
          img.alt = "";
          if (existing) existing.replaceWith(img);
          else slideEl.appendChild(img);
        }
      });
      if (window.refreshHeroPanels) window.refreshHeroPanels();
      if (window.setHeroPanelTitleSettings) window.setHeroPanelTitleSettings(res.settings, currentLang);
      if (window.setHeroPanelLinks) window.setHeroPanelLinks(res.settings);
    }

    // ── Products ──
    products = res.products
      .filter((p) => p.status === "active" && Number(p.stock) > 0);
    renderProducts(currentLang);

    // ── Bundle banner ──
    const bundle = res.bundle || {};
    if (bundle.bundleId) {
      _bundleId = bundle.bundleId;
      _bundleText = {
        titleEn:       bundle.titleEn       || "",
        titleFr:       bundle.titleFr       || "",
        titleAr:       bundle.titleAr       || "",
        descriptionEn: bundle.descriptionEn || "",
        descriptionFr: bundle.descriptionFr || "",
        descriptionAr: bundle.descriptionAr || "",
      };
      updateBannerLang(currentLang);
      const product = res.products.find(
        (p) => p.id === bundle.bundleId && p.status === "active" && Number(p.stock) > 0,
      );
      if (product) {
        const img = document.getElementById("bundleBannerImg");
        const link = document.getElementById("bundleBannerLink");
        const _bundleImg0 = Array.isArray(product.imageUrl) ? product.imageUrl[0] : product.imageUrl;
        if (img && _bundleImg0) { img.src = _bundleImg0; img.style.display = ""; }
        if (link) link.href = `/product-detail?id=${product.id}`;
        const section = document.getElementById("featuredBannerSection");
        if (section) section.style.display = "";
      }
    }

    // ── Categories ──
    _categories = res.categories || [];
    _subCategories = res.subCategories || [];
    _subSubCategories = res.subSubCategories || [];
    renderCatNav();
    renderCategoryGrid();

    // ── Facebook Pixel ──
    if (window.TaurusPixel && res.settings) {
      window.TaurusPixel.init(res.settings);
    }
  } catch (err) {
    console.error("Failed to load initial data:", err);
  }
  hideLoader();
}

