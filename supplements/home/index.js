// 3. Scroll reveal with IntersectionObserver
(function() {
  var obs = new IntersectionObserver(function(entries) {
    entries.forEach(function(e) {
      if (e.isIntersecting) { e.target.classList.add('visible'); obs.unobserve(e.target); }
    });
  }, { threshold: 0.12 });
  window._homeRevealObserver = obs;
  document.querySelectorAll('.reveal').forEach(function(el) { obs.observe(el); });
})();

// 4. Product card 3D tilt on mouse move
(function() {
  function addTilt(card) {
    card.addEventListener('mousemove', function(e) {
      var rect = card.getBoundingClientRect();
      var cx = rect.left + rect.width / 2;
      var cy = rect.top + rect.height / 2;
      var dx = (e.clientX - cx) / (rect.width / 2);
      var dy = (e.clientY - cy) / (rect.height / 2);
      card.style.transform = 'perspective(600px) rotateY(' + (dx * 4) + 'deg) rotateX(' + (-dy * 4) + 'deg) translateY(-2px)';
    });
    card.style.transformStyle = 'preserve-3d';
    card.addEventListener('mouseleave', function() {
      card.style.transform = '';
    });
  }
  document.querySelectorAll('.product-card').forEach(addTilt);
  var gridObs = new MutationObserver(function(muts) {
    muts.forEach(function(m) {
      m.addedNodes.forEach(function(n) {
        if (n.nodeType === 1) {
          if (n.classList && n.classList.contains('product-card')) addTilt(n);
          n.querySelectorAll && n.querySelectorAll('.product-card').forEach(addTilt);
        }
      });
    });
  });
  var grid = document.getElementById('productGrid');
  if (grid) gridObs.observe(grid, { childList: true, subtree: true });
})();

// 5. Button ripple on click
(function() {
  document.addEventListener('click', function(e) {
    var btn = e.target.closest('.btn-primary, .btn-outline, .btn-send');
    if (!btn) return;
    var rect = btn.getBoundingClientRect();
    var r = document.createElement('span');
    var d = Math.max(rect.width, rect.height);
    r.className = 'ripple-wave';
    r.style.cssText = 'position: absolute; border-radius: 50%; background: rgba(255,255,255,0.15); pointer-events: none; transform: scale(0); animation: ripple 0.6s linear; width:' + d + 'px;height:' + d + 'px;left:' + (e.clientX - rect.left - d/2) + 'px;top:' + (e.clientY - rect.top - d/2) + 'px;';
    btn.appendChild(r);
    r.addEventListener('animationend', function() { r.remove(); });
  });
})();

// 6. Count-up for hero stats
(function() {
  var counters = document.querySelectorAll('.stat-num[data-count]');
  if (!counters.length) return;
  var obs = new IntersectionObserver(function(entries) {
    entries.forEach(function(e) {
      if (!e.isIntersecting) return;
      var el = e.target;
      var target = parseInt(el.dataset.count, 10);
      var suffix = el.dataset.suffix || '';
      var duration = 1400;
      var start = performance.now();
      function step(now) {
        var progress = Math.min((now - start) / duration, 1);
        var ease = 1 - Math.pow(1 - progress, 3);
        el.textContent = Math.floor(ease * target) + suffix;
        if (progress < 1) requestAnimationFrame(step);
      }
      requestAnimationFrame(step);
      obs.unobserve(el);
    });
  }, { threshold: 0.5 });
  counters.forEach(function(c) { obs.observe(c); });
})();
