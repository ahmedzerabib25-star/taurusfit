  const flavorObjs = (Array.isArray(product.flavors) ? product.flavors : (typeof product.flavors === 'string' ? JSON.parse(product.flavors) : [])).map(f => typeof f === 'object' ? { name: f.name || '', qty: f.qty || 0 } : { name: String(f), qty: 0 });
