/* ─────────────────────────────────────────────────────────────
   LANGUAGE SWITCHER
   - Switches UI text for elements with data-i18n / data-i18n-html
───────────────────────────────────────────────────────────── */
function switchLang(lang) {
  localStorage.setItem("bybens_lang", lang);

  currentLang = lang;
  const t = i18n[lang];
  const isRtl = lang === "ar";
  document.documentElement.lang = lang;
  document.documentElement.dir = isRtl ? "rtl" : "ltr";
  document.body.classList.toggle("lang-ar", isRtl);

  // Update all translatable text nodes
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (t[key]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = t[key];
      } else el.textContent = t[key];
    }
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (t[key]) el.innerHTML = t[key];
  });

  // Update lang buttons
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  // Re-render products with new button labels
  renderProducts(lang);

  // Re-render category nav + grid in new language
  renderCatNav();
  renderCategoryGrid();

  // Update bundle banner text
  updateBannerLang(lang);

  // Sanitize footer and modals for correct brand naming
  sanitizeFooterAndModals(lang);
}

